SELECT CONVERT(INT, CONVERT(CHAR(8), S.fecha, 112)),
       C.sk_cliente, T.sk_trabajador, P.sk_producto, CV.sk_condicion_venta,
       100000 + ((S.n-1)/3), RIGHT('000000' + CONVERT(VARCHAR(6), ((S.n-1)%3)+1), 6), S.cant,
       CAST(P.precio_lista * S.cant * (0.94 + ((S.n % 12) / 100.0)) AS DECIMAL(12,2))
FROM S
JOIN dbo.Dim_Cliente C ON C.id_cliente = RIGHT('000000' + CONVERT(VARCHAR(6), S.cli), 6) AND C.es_vigente=1
JOIN dbo.Dim_Trabajador T ON T.id_trabajador = RIGHT('000000' + CONVERT(VARCHAR(6), S.trab), 6) AND T.es_vigente=1
JOIN dbo.Dim_Producto P ON P.cod_producto = RIGHT('000000' + CONVERT(VARCHAR(6), S.prod), 6)
