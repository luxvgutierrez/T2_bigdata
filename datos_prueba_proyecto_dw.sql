-- 8. Fact_Ventas: 5,000 líneas. Las fechas, claves y precios son coherentes.
;WITH N AS (
    SELECT TOP (5000) ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS n
    FROM sys.all_objects a CROSS JOIN sys.all_objects b
), S AS (
    SELECT n,
           DATEADD(DAY, (n * 7 + (n % 29)) % (DATEDIFF(DAY,'2025-01-01','2026-09-30') + 1), CAST('2025-01-01' AS DATE)) AS fecha,
           ((n * 13) % 80) + 1 AS prod,
           ((n * 17) % 300) + 1 AS cli,
           ((n * 7) % 20) + 1 AS trab,
           ((n * 3) % 10) + 1 AS cond,
           1 + (n % 4) AS cant
    FROM N
)
