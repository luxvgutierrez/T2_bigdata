-- 10. Fact_Inventario_Snapshot: stock diario por producto (80 x cada fecha).
;WITH N AS (
    SELECT TOP (DATEDIFF(DAY,'2025-01-01','2026-09-30')+1)
           ROW_NUMBER() OVER (ORDER BY (SELECT NULL))-1 AS n
    FROM sys.all_objects a CROSS JOIN sys.all_objects b
), Fechas AS (
    SELECT DATEADD(DAY,n,CAST('2025-01-01' AS DATE)) AS fecha FROM N
), Productos AS (
    SELECT sk_producto FROM dbo.Dim_Producto
)
INSERT INTO dbo.Fact_Inventario_Snapshot (sk_tiempo,sk_producto,stock_cantidad)
SELECT CONVERT(INT,CONVERT(CHAR(8),F.fecha,112)), P.sk_producto,
       CASE WHEN (DATEPART(DAY,F.fecha)+P.sk_producto*3)%19=0 THEN (P.sk_producto%5)
            ELSE 15 + ((P.sk_producto*17 + DATEPART(DAYOFYEAR,F.fecha)*3 + MONTH(F.fecha)*7)%180) END
FROM Fechas F CROSS JOIN Productos P;
GO

